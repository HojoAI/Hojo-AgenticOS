package com.hojoai.webmvc.omniasst.meeting.api.dto;

/**
 * 消息中心「创建进程任务」请求体，与 management {@code CreateTaskRequest} 字段对齐。
 */
public class MessageCenterCreateTaskRequest {

    private String userId;

    private String type;

    private String title;

    private String progressText;

    private Integer estimatedSeconds;

    private String relatedId;

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getProgressText() {
        return progressText;
    }

    public void setProgressText(String progressText) {
        this.progressText = progressText;
    }

    public Integer getEstimatedSeconds() {
        return estimatedSeconds;
    }

    public void setEstimatedSeconds(Integer estimatedSeconds) {
        this.estimatedSeconds = estimatedSeconds;
    }

    public String getRelatedId() {
        return relatedId;
    }

    public void setRelatedId(String relatedId) {
        this.relatedId = relatedId;
    }
}
