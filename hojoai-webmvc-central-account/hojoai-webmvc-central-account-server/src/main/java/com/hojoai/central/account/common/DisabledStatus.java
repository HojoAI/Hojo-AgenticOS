package com.hojoai.central.account.common;

/**
 * 用户账号禁用状态（持久化字段取值）。
 */
public enum DisabledStatus {

    /** 未禁用 */
    NON(1, "未禁用"),
    /** 已禁用 */
    ALREADY(2, "已禁用");

    private int code;
    private String desc;

    DisabledStatus(int code, String desc) {
        this.code = code;
        this.desc = desc;
    }

    public int getCode() {
        return code;
    }

    public void setCode(int code) {
        this.code = code;
    }

    public String getDesc() {
        return desc;
    }

    public void setDesc(String desc) {
        this.desc = desc;
    }
}
