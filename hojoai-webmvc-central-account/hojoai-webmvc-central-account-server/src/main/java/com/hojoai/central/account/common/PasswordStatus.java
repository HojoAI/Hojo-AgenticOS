package com.hojoai.central.account.common;

/**
 * 用户密码是否已设置（业务展示或持久化含义）。
 */
public enum PasswordStatus {

    /** 未设置密码 */
    NON(1, "未设置"),
    /** 已设置密码 */
    ALREADY(2, "已设置");

    private int code;
    private String desc;

    PasswordStatus(int code, String desc) {
        this.code = code;
        this.desc = desc;
    }

    public int getCode() {
        return code;
    }

    public void setCode(int code) {
        this.code = code;
    }

    public String getDesc() {
        return desc;
    }

    public void setDesc(String desc) {
        this.desc = desc;
    }
}
